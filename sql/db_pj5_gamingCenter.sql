-- Módulos ocupados ahora mismo y por quién:
SELECT s.nombre AS sala, m.codigo, g.username, o.num_jugadores, o.fecha_inicio
FROM ocupaciones o JOIN modulos m ON m.id_modulo = o.id_modulo
JOIN salas s ON s.id_sala = m.id_sala
JOIN gamemasters g ON g.id_gamemaster = o.id_gamemaster
WHERE o.fecha_fin IS NULL;