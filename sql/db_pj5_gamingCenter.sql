SET NAMES utf8mb4;
DROP DATABASE IF EXISTS gamingCenter;
CREATE DATABASE gamingCenter CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE gamingCenter;

-- ---------- ESTRUCTURA ----------

DROP TABLE IF EXISTS ocupaciones;
DROP TABLE IF EXISTS gamemasters;
DROP TABLE IF EXISTS roles;
DROP TABLE IF EXISTS puestos_juego;
DROP TABLE IF EXISTS modulos;
DROP TABLE IF EXISTS tipos_modulo;
DROP TABLE IF EXISTS salas;
DROP TABLE IF EXISTS zonas;

CREATE TABLE zonas (
  id_zona      INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre       VARCHAR(50)  NOT NULL,
  activo       TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_zona),
  UNIQUE KEY uq_zonas_nombre (nombre)
) ENGINE=InnoDB;

CREATE TABLE salas (
  id_sala  INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre   VARCHAR(50)  NOT NULL,
  id_zona  INT UNSIGNED NOT NULL,
  activo   TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_sala),
  UNIQUE KEY uq_salas_nombre (nombre),
  KEY idx_salas_zona_activo (id_zona, activo),
  CONSTRAINT fk_salas_zona FOREIGN KEY (id_zona) REFERENCES zonas (id_zona)
    ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE tipos_modulo (
  id_tipo_modulo INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre         VARCHAR(40)  NOT NULL,
  capacidad      TINYINT UNSIGNED NOT NULL,
  activo         TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_tipo_modulo),
  UNIQUE KEY uq_tipos_modulo_nombre (nombre),
  CONSTRAINT chk_tipos_modulo_capacidad CHECK (capacidad > 0)
) ENGINE=InnoDB;

CREATE TABLE roles (
  id_rol INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre VARCHAR(30) NOT NULL,
  PRIMARY KEY (id_rol),
  UNIQUE KEY uq_roles_nombre (nombre)
) ENGINE=InnoDB;

CREATE TABLE modulos (
  id_modulo      INT UNSIGNED NOT NULL AUTO_INCREMENT,
  codigo         VARCHAR(10)  NOT NULL,
  id_sala        INT UNSIGNED NOT NULL,
  id_tipo_modulo INT UNSIGNED NOT NULL,
  activo         TINYINT(1)   NOT NULL DEFAULT 1,
  PRIMARY KEY (id_modulo),
  UNIQUE KEY uq_modulos_sala_codigo (id_sala, codigo),
  CONSTRAINT fk_modulos_sala FOREIGN KEY (id_sala) REFERENCES salas (id_sala)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_modulos_tipo FOREIGN KEY (id_tipo_modulo) REFERENCES tipos_modulo (id_tipo_modulo)
    ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE puestos_juego (
  id_puesto INT UNSIGNED NOT NULL AUTO_INCREMENT,
  codigo    VARCHAR(20)  NOT NULL,
  id_modulo INT UNSIGNED NOT NULL,
  PRIMARY KEY (id_puesto),
  UNIQUE KEY uq_puestos_codigo (codigo),
  CONSTRAINT fk_puestos_modulo FOREIGN KEY (id_modulo) REFERENCES modulos (id_modulo)
    ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE gamemasters (
  id_gamemaster INT UNSIGNED NOT NULL AUTO_INCREMENT,
  username      VARCHAR(30)  NOT NULL,
  password      VARCHAR(255) NOT NULL,
  nombre        VARCHAR(50)  NOT NULL,
  apellido      VARCHAR(80)  NOT NULL,
  activo        TINYINT(1)   NOT NULL DEFAULT 1,
  id_rol        INT UNSIGNED NOT NULL,
  PRIMARY KEY (id_gamemaster),
  UNIQUE KEY uq_gamemasters_username (username),
  KEY idx_gamemasters_rol (id_rol),
  CONSTRAINT fk_gamemasters_rol FOREIGN KEY (id_rol) REFERENCES roles (id_rol)
    ON DELETE RESTRICT ON UPDATE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE ocupaciones (
  id_ocupacion  INT UNSIGNED NOT NULL AUTO_INCREMENT,
  id_modulo     INT UNSIGNED NOT NULL,
  id_gamemaster INT UNSIGNED NOT NULL,
  nombre_gamemaster_snapshot VARCHAR(50) NULL,
  apellido_gamemaster_snapshot VARCHAR(80) NULL,
  num_jugadores TINYINT UNSIGNED NOT NULL,
  fecha_inicio  DATETIME NOT NULL,
  fecha_fin     DATETIME NULL DEFAULT NULL,
  id_zona_snapshot INT UNSIGNED NULL,
  id_sala_snapshot INT UNSIGNED NULL,
  nombre_zona_snapshot VARCHAR(50) NULL,
  nombre_sala_snapshot VARCHAR(50) NULL,
  codigo_modulo_snapshot VARCHAR(10) NULL,
  tipo_modulo_snapshot VARCHAR(40) NULL,
  capacidad_modulo_snapshot TINYINT UNSIGNED NULL,
  PRIMARY KEY (id_ocupacion),
  KEY idx_ocupaciones_modulo_fin (id_modulo, fecha_fin),
  KEY idx_ocupaciones_inicio (fecha_inicio),
  KEY idx_ocupaciones_zona_hist (id_zona_snapshot, fecha_inicio),
  KEY idx_ocupaciones_sala_hist (id_sala_snapshot, fecha_inicio),
  KEY idx_ocupaciones_gamemaster (id_gamemaster),
  CONSTRAINT fk_ocupaciones_modulo FOREIGN KEY (id_modulo) REFERENCES modulos (id_modulo)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT fk_ocupaciones_gamemaster FOREIGN KEY (id_gamemaster) REFERENCES gamemasters (id_gamemaster)
    ON DELETE RESTRICT ON UPDATE RESTRICT,
  CONSTRAINT chk_ocupaciones_jugadores CHECK (num_jugadores >= 1),
  CONSTRAINT chk_ocupaciones_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
) ENGINE=InnoDB;

